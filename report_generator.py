
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    KeepTogether,
)


def generate_comparison_report(
    comparison,
    document_a_name,
    document_b_name,
):
    """Generate a downloadable PDF from Gemini comparison results."""

    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title="AI Document Comparison Report",
        author="AI Document Comparison Assistant",
    )

    styles = getSampleStyleSheet()

    styles.add(
        ParagraphStyle(
            name="ReportTitle",
            parent=styles["Title"],
            alignment=TA_CENTER,
            fontSize=20,
            leading=25,
            textColor=colors.HexColor("#17365D"),
            spaceAfter=8,
        )
    )

    styles.add(
        ParagraphStyle(
            name="SectionHeading",
            parent=styles["Heading2"],
            fontSize=13,
            leading=17,
            textColor=colors.HexColor("#17365D"),
            spaceBefore=12,
            spaceAfter=6,
        )
    )

    styles.add(
        ParagraphStyle(
            name="SmallText",
            parent=styles["BodyText"],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#555555"),
            spaceAfter=5,
        )
    )

    story = []

    def safe_text(value):
        """Escape text so document contents cannot break PDF markup."""
        if value is None:
            return "Not provided"
        return escape(str(value)).replace("\n", "<br/>")

    def add_paragraph(text, style="BodyText"):
        story.append(Paragraph(safe_text(text), styles[style]))

    def add_bullet(text):
        story.append(
            Paragraph(
                "&#8226; " + safe_text(text),
                styles["BodyText"],
            )
        )
        story.append(Spacer(1, 4))

    def add_findings(title, findings):
        story.append(Paragraph(title, styles["SectionHeading"]))

        if not findings:
            add_paragraph("No findings were returned.")
            return

        for item in findings:
            if isinstance(item, dict):
                finding = item.get("finding", "Finding not provided")
                evidence_a = item.get(
                    "document_a_evidence", "Not provided"
                )
                page_a = item.get("document_a_page")
                evidence_b = item.get(
                    "document_b_evidence", "Not provided"
                )
                page_b = item.get("document_b_page")

                block = [
                    Paragraph(
                        safe_text(finding),
                        styles["Heading3"],
                    ),
                    Paragraph(
                        "<b>Document A evidence:</b> "
                        + safe_text(evidence_a),
                        styles["SmallText"],
                    ),
                    Paragraph(
                        "<b>Document A page:</b> "
                        + safe_text(page_a),
                        styles["SmallText"],
                    ),
                    Paragraph(
                        "<b>Document B evidence:</b> "
                        + safe_text(evidence_b),
                        styles["SmallText"],
                    ),
                    Paragraph(
                        "<b>Document B page:</b> "
                        + safe_text(page_b),
                        styles["SmallText"],
                    ),
                    Spacer(1, 7),
                ]
                story.append(KeepTogether(block))
            else:
                add_bullet(item)

    story.append(
        Paragraph("AI Document Comparison Report", styles["ReportTitle"])
    )
    story.append(
        Paragraph(
            "Generated by AI Document Comparison Assistant",
            styles["SmallText"],
        )
    )
    story.append(Spacer(1, 8))

    story.append(
        Paragraph("Compared Documents", styles["SectionHeading"])
    )

    document_table = [
        [
            Paragraph("<b>Document A</b>", styles["BodyText"]),
            Paragraph("<b>Document B</b>", styles["BodyText"]),
        ],
        [
            Paragraph(safe_text(document_a_name), styles["BodyText"]),
            Paragraph(safe_text(document_b_name), styles["BodyText"]),
        ],
    ]

    table = Table(document_table, colWidths=[85 * mm, 85 * mm])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#D9EAF7")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ]
        )
    )
    story.append(table)
    story.append(Spacer(1, 10))

    story.append(
        Paragraph("Document Summaries", styles["SectionHeading"])
    )
    story.append(Paragraph("<b>Document A</b>", styles["BodyText"]))
    add_paragraph(comparison.get("summary_a", "No summary provided"))
    story.append(Paragraph("<b>Document B</b>", styles["BodyText"]))
    add_paragraph(comparison.get("summary_b", "No summary provided"))

    add_findings(
        "Similarities",
        comparison.get("similarities", []),
    )
    add_findings(
        "Differences",
        comparison.get("differences", []),
    )

    story.append(
        Paragraph("Key Details", styles["SectionHeading"])
    )
    for detail in comparison.get("key_details", []):
        add_bullet(detail)

    story.append(
        Paragraph("Limitations and Cautions", styles["SectionHeading"])
    )
    for limitation in comparison.get("limitations", []):
        add_bullet(limitation)

    story.append(Spacer(1, 14))
    story.append(
        Paragraph(
            "Disclaimer: This report contains AI-generated analysis. "
            "Verify all findings, quotations, and page references against "
            "the original documents. It is informational assistance, "
            "not legal advice.",
            styles["SmallText"],
        )
    )

    doc.build(story)

    buffer.seek(0)
    return buffer.getvalue()
